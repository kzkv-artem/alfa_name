_BASE_RULES = """Ты — ассистент Альфа-Банка для предпринимателей.

Жёсткие правила:
- Пиши по-русски, просто, без канцелярита и без англицизмов.
- Никакого markdown: ни звёздочек, ни решёток, ни списков через дефис.
- Ни одну цифру из входных данных не меняй и не округляй самостоятельно.
- Не выдумывай факты, которых нет во входных данных. Не знаешь — не пиши.
- Не обещай одобрение, выплату или конкретный результат.
- Не подгоняй клиента и не пугай его."""

_PLACEHOLDER_RE = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")


@dataclass(frozen=True)
class PromptTemplate:

    name: str
    system: str
    user: str
    description: str = ""

    @property
    def variables(self) -> frozenset[str]:
        return frozenset(_PLACEHOLDER_RE.findall(self.user))

    def render(self, **kwargs) -> tuple[str, str]:
        required = self.variables
        provided = set(kwargs)

        missing = required - provided
        if missing:
            raise KeyError(
                f"Шаблон {self.name!r}: не переданы переменные {sorted(missing)}"
            )

        extra = provided - required
        if extra:
            raise ValueError(
                f"Шаблон {self.name!r}: переданы лишние переменные {sorted(extra)}"
            )

        return self.system, self.user.format(**kwargs)


TEMPLATES: dict[str, PromptTemplate] = {}


def register(template: PromptTemplate) -> PromptTemplate:
    if template.name in TEMPLATES:
        raise ValueError(f"Шаблон {template.name!r} уже зарегистрирован")
    TEMPLATES[template.name] = template
    return template


def get_template(name: str) -> PromptTemplate:
    try:
        return TEMPLATES[name]
    except KeyError as exc:
        known = ", ".join(sorted(TEMPLATES)) or "реестр пуст"
        raise KeyError(f"Нет шаблона {name!r}. Доступные: {known}") from exc


def render(name: str, **kwargs) -> tuple[str, str]:
    return get_template(name).render(**kwargs)


def list_templates() -> list[str]:
    return sorted(TEMPLATES)


